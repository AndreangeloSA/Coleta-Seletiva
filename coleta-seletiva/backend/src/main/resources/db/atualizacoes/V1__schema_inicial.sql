-- Sistema de Coleta Seletiva
-- PostgreSQL - esquema alinhado às entidades JPA do backend.
-- Execute dentro do banco já criado (por exemplo, coleta_seletiva).
-- O script é idempotente para criação inicial e acrescenta as colunas novas
-- documentadas abaixo sem apagar registros existentes.

CREATE TABLE IF NOT EXISTS morador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    telefone VARCHAR(255),
    CONSTRAINT uk_morador_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS endereco (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    morador_id BIGINT NOT NULL,
    logradouro VARCHAR(255) NOT NULL,
    numero VARCHAR(255),
    bairro VARCHAR(255) NOT NULL,
    municipio VARCHAR(255) NOT NULL,
    uf VARCHAR(2) NOT NULL,
    cep VARCHAR(9) NOT NULL,
    complemento VARCHAR(255),
    sem_numero BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_endereco_morador
        FOREIGN KEY (morador_id) REFERENCES morador(id) ON DELETE RESTRICT,
    CONSTRAINT ck_endereco_numero CHECK (
        (sem_numero = TRUE AND (numero IS NULL OR BTRIM(numero) = ''))
        OR (sem_numero = FALSE AND numero IS NOT NULL AND BTRIM(numero) <> '')
    )
);

CREATE TABLE IF NOT EXISTS ponto_coleta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    endereco VARCHAR(500) NOT NULL,
    contato VARCHAR(255),
    horarios_funcionamento VARCHAR(500),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    recolhimento_domiciliar BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS material (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    descricao VARCHAR(2000),
    unidade_medida VARCHAR(255) NOT NULL,
    orientacao_preparo VARCHAR(2000),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_material_nome UNIQUE (nome)
);

CREATE TABLE IF NOT EXISTS material_aceito (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ponto_id BIGINT NOT NULL,
    material_id BIGINT NOT NULL,
    observacoes VARCHAR(255),
    limite_por_solicitacao NUMERIC(12,3),
    CONSTRAINT fk_material_aceito_ponto
        FOREIGN KEY (ponto_id) REFERENCES ponto_coleta(id) ON DELETE RESTRICT,
    CONSTRAINT fk_material_aceito_material
        FOREIGN KEY (material_id) REFERENCES material(id) ON DELETE RESTRICT,
    CONSTRAINT uk_ponto_material UNIQUE (ponto_id, material_id),
    CONSTRAINT ck_material_aceito_limite
        CHECK (limite_por_solicitacao IS NULL OR limite_por_solicitacao > 0)
);

CREATE TABLE IF NOT EXISTS operador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    CONSTRAINT uk_operador_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS operador_ponto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operador_id BIGINT NOT NULL,
    ponto_id BIGINT NOT NULL,
    CONSTRAINT fk_operador_ponto_operador
        FOREIGN KEY (operador_id) REFERENCES operador(id) ON DELETE RESTRICT,
    CONSTRAINT fk_operador_ponto_ponto
        FOREIGN KEY (ponto_id) REFERENCES ponto_coleta(id) ON DELETE RESTRICT,
    CONSTRAINT uk_operador_ponto UNIQUE (operador_id, ponto_id)
);

CREATE TABLE IF NOT EXISTS solicitacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocolo VARCHAR(255) NOT NULL,
    morador_id BIGINT NOT NULL,
    ponto_id BIGINT NOT NULL,
    logradouro VARCHAR(255) NOT NULL,
    numero VARCHAR(255),
    sem_numero BOOLEAN NOT NULL DEFAULT FALSE,
    bairro VARCHAR(255) NOT NULL,
    municipio VARCHAR(255) NOT NULL,
    uf VARCHAR(2) NOT NULL,
    cep VARCHAR(9) NOT NULL,
    complemento VARCHAR(255),
    situacao VARCHAR(50) NOT NULL,
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL,
    data_agendamento TIMESTAMP WITH TIME ZONE,
    observacoes VARCHAR(1000),
    versao BIGINT NOT NULL DEFAULT 0,
    data_atualizacao TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_solicitacao_protocolo UNIQUE (protocolo),
    CONSTRAINT fk_solicitacao_morador
        FOREIGN KEY (morador_id) REFERENCES morador(id) ON DELETE RESTRICT,
    CONSTRAINT fk_solicitacao_ponto
        FOREIGN KEY (ponto_id) REFERENCES ponto_coleta(id) ON DELETE RESTRICT,
    CONSTRAINT ck_solicitacao_situacao CHECK (situacao IN (
        'SOLICITADA', 'AGENDADA', 'EM_RECOLHIMENTO',
        'CONCLUIDA', 'RECUSADA', 'CANCELADA'
    )),
    CONSTRAINT ck_solicitacao_versao CHECK (versao >= 0),
    CONSTRAINT ck_solicitacao_numero CHECK (
        (sem_numero = TRUE AND (numero IS NULL OR BTRIM(numero) = ''))
        OR (sem_numero = FALSE AND numero IS NOT NULL AND BTRIM(numero) <> '')
    )
);

CREATE TABLE IF NOT EXISTS item_solicitacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id BIGINT NOT NULL,
    material_id BIGINT NOT NULL,
    unidade VARCHAR(255) NOT NULL,
    quantidade_estimada NUMERIC(14,3) NOT NULL,
    quantidade_efetiva NUMERIC(14,3),
    CONSTRAINT fk_item_solicitacao_solicitacao
        FOREIGN KEY (solicitacao_id) REFERENCES solicitacao(id) ON DELETE RESTRICT,
    CONSTRAINT fk_item_solicitacao_material
        FOREIGN KEY (material_id) REFERENCES material(id) ON DELETE RESTRICT,
    CONSTRAINT uk_item_solicitacao_material UNIQUE (solicitacao_id, material_id),
    CONSTRAINT ck_item_quantidade_estimada CHECK (quantidade_estimada > 0),
    CONSTRAINT ck_item_quantidade_efetiva CHECK (quantidade_efetiva IS NULL OR quantidade_efetiva >= 0)
);

CREATE TABLE IF NOT EXISTS historico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id BIGINT NOT NULL,
    situacao_anterior VARCHAR(50),
    situacao_nova VARCHAR(50) NOT NULL,
    data_hora TIMESTAMP WITH TIME ZONE NOT NULL,
    responsavel VARCHAR(255),
    motivo VARCHAR(255),
    dados_tentativa VARCHAR(255),
    CONSTRAINT fk_historico_solicitacao
        FOREIGN KEY (solicitacao_id) REFERENCES solicitacao(id) ON DELETE RESTRICT,
    CONSTRAINT ck_historico_situacao_nova CHECK (situacao_nova IN (
        'SOLICITADA', 'AGENDADA', 'EM_RECOLHIMENTO',
        'CONCLUIDA', 'RECUSADA', 'CANCELADA'
    )),
    CONSTRAINT ck_historico_situacao_anterior CHECK (
        situacao_anterior IS NULL OR situacao_anterior IN (
            'SOLICITADA', 'AGENDADA', 'EM_RECOLHIMENTO',
            'CONCLUIDA', 'RECUSADA', 'CANCELADA'
        )
    )
);

-- Compatibilidade com bancos criados por versões anteriores do schema.
ALTER TABLE endereco ADD COLUMN IF NOT EXISTS sem_numero BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE solicitacao ADD COLUMN IF NOT EXISTS sem_numero BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE solicitacao ADD COLUMN IF NOT EXISTS versao BIGINT NOT NULL DEFAULT 0;
ALTER TABLE solicitacao ADD COLUMN IF NOT EXISTS data_atualizacao TIMESTAMP WITH TIME ZONE;

-- Índices usados nas consultas e nos filtros dos requisitos RF06, RF09 e RF15.
CREATE INDEX IF NOT EXISTS idx_endereco_morador ON endereco(morador_id);
CREATE INDEX IF NOT EXISTS idx_ponto_coleta_ativo ON ponto_coleta(ativo);
CREATE INDEX IF NOT EXISTS idx_material_aceito_ponto ON material_aceito(ponto_id);
CREATE INDEX IF NOT EXISTS idx_material_aceito_material ON material_aceito(material_id);
CREATE INDEX IF NOT EXISTS idx_operador_ponto_operador ON operador_ponto(operador_id);
CREATE INDEX IF NOT EXISTS idx_operador_ponto_ponto ON operador_ponto(ponto_id);
CREATE INDEX IF NOT EXISTS idx_solicitacao_morador ON solicitacao(morador_id);
CREATE INDEX IF NOT EXISTS idx_solicitacao_ponto ON solicitacao(ponto_id);
CREATE INDEX IF NOT EXISTS idx_solicitacao_situacao ON solicitacao(situacao);
CREATE INDEX IF NOT EXISTS idx_solicitacao_data_criacao ON solicitacao(data_criacao);
CREATE INDEX IF NOT EXISTS idx_solicitacao_ponto_situacao_data
    ON solicitacao(ponto_id, situacao, data_criacao);
CREATE INDEX IF NOT EXISTS idx_item_solicitacao_solicitacao ON item_solicitacao(solicitacao_id);
CREATE INDEX IF NOT EXISTS idx_item_solicitacao_material ON item_solicitacao(material_id);
CREATE INDEX IF NOT EXISTS idx_historico_solicitacao_data ON historico(solicitacao_id, data_hora);

