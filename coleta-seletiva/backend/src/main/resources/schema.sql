-- 8. SOLICITACAO (RF08 a RF14)
-- Guarda a cópia histórica do endereço usada no pedido (RN04).
-- ponto_id referencia ponto_coleta, embora na entidade Java seja Long.
-- ============================================================
CREATE TABLE IF NOT EXISTS solicitacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocolo VARCHAR(255) NOT NULL,
    morador_id BIGINT NOT NULL,
    ponto_id BIGINT NOT NULL,

    logradouro VARCHAR(255) NOT NULL,
    numero VARCHAR(255),
    bairro VARCHAR(255) NOT NULL,
    municipio VARCHAR(255) NOT NULL,
    uf VARCHAR(2) NOT NULL,
    cep VARCHAR(9) NOT NULL,
    complemento VARCHAR(255),

    situacao VARCHAR(50) NOT NULL,
    data_criacao TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    data_agendamento TIMESTAMP WITHOUT TIME ZONE,
    observacoes VARCHAR(255),
    versao BIGINT NOT NULL DEFAULT 0,
    data_atualizacao TIMESTAMP WITHOUT TIME ZONE,

    CONSTRAINT uk_solicitacao_protocolo UNIQUE (protocolo),
    CONSTRAINT fk_solicitacao_morador
        FOREIGN KEY (morador_id) REFERENCES morador(id) ON DELETE RESTRICT,
    CONSTRAINT fk_solicitacao_ponto
        FOREIGN KEY (ponto_id) REFERENCES ponto_coleta(id) ON DELETE RESTRICT,
    CONSTRAINT ck_solicitacao_situacao
        CHECK (situacao IN (
            'SOLICITADA',
            'AGENDADA',
            'EM_RECOLHIMENTO',
            'CONCLUIDA',
            'RECUSADA',
            'CANCELADA'
        )),
    CONSTRAINT ck_solicitacao_versao
        CHECK (versao >= 0)
);

CREATE INDEX IF NOT EXISTS idx_solicitacao_morador
    ON solicitacao(morador_id);

CREATE INDEX IF NOT EXISTS idx_solicitacao_ponto
    ON solicitacao(ponto_id);

CREATE INDEX IF NOT EXISTS idx_solicitacao_situacao
    ON solicitacao(situacao);

CREATE INDEX IF NOT EXISTS idx_solicitacao_data_criacao
    ON solicitacao(data_criacao);

-- Índice composto útil para consultas filtradas por ponto, situação e período.
CREATE INDEX IF NOT EXISTS idx_solicitacao_ponto_situacao_data
    ON solicitacao(ponto_id, situacao, data_criacao);
-- ============================================================
-- 9. ITEM_SOLICITACAO (RF08 e RF13)
-- A unidade é copiada para preservar o histórico (RN04).
-- ============================================================
CREATE TABLE IF NOT EXISTS item_solicitacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id BIGINT NOT NULL,
    material_id BIGINT NOT NULL,
    unidade VARCHAR(255) NOT NULL,
    quantidade_estimada NUMERIC(12,3) NOT NULL,
    quantidade_efetiva NUMERIC(12,3),

    CONSTRAINT fk_item_solicitacao_solicitacao
        FOREIGN KEY (solicitacao_id) REFERENCES solicitacao(id) ON DELETE RESTRICT,
    CONSTRAINT fk_item_solicitacao_material
        FOREIGN KEY (material_id) REFERENCES material(id) ON DELETE RESTRICT,
    CONSTRAINT uk_solicitacao_material
        UNIQUE (solicitacao_id, material_id),
    CONSTRAINT ck_item_quantidade_estimada
        CHECK (quantidade_estimada > 0),
    CONSTRAINT ck_item_quantidade_efetiva
        CHECK (quantidade_efetiva IS NULL OR quantidade_efetiva >= 0)
);

CREATE INDEX IF NOT EXISTS idx_item_solicitacao_solicitacao
    ON item_solicitacao(solicitacao_id);

CREATE INDEX IF NOT EXISTS idx_item_solicitacao_material
    ON item_solicitacao(material_id);

-- ============================================================
-- 10. HISTORICO (RN03 e RF09)
-- Registra as mudanças de situação e as tentativas de atendimento.
-- ============================================================
CREATE TABLE IF NOT EXISTS historico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id BIGINT NOT NULL,
    situacao_anterior VARCHAR(50),
    situacao_nova VARCHAR(50) NOT NULL,
    data_hora TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    responsavel VARCHAR(255),
    motivo VARCHAR(255),
    dados_tentativa VARCHAR(255),

    CONSTRAINT fk_historico_solicitacao
        FOREIGN KEY (solicitacao_id) REFERENCES solicitacao(id) ON DELETE RESTRICT,
    CONSTRAINT ck_historico_situacao_anterior
        CHECK (
            situacao_anterior IS NULL
            OR situacao_anterior IN (
                'SOLICITADA', 'AGENDADA', 'EM_RECOLHIMENTO',
                'CONCLUIDA', 'RECUSADA', 'CANCELADA'
            )
        ),
    CONSTRAINT ck_historico_situacao_nova
        CHECK (situacao_nova IN (
            'SOLICITADA', 'AGENDADA', 'EM_RECOLHIMENTO',
            'CONCLUIDA', 'RECUSADA', 'CANCELADA'
        ))
);

CREATE INDEX IF NOT EXISTS idx_historico_solicitacao_data
    ON historico(solicitacao_id, data_hora);

